#!/bin/sh
# nginx docker-entrypoint.d hook: prepares /setup. sc-lsp keeps the GUI admin
# token in <storage_dir>/<network>/gui.macaroon (mounted read-only at
# /run/sc-lsp), private to its own user, so nginx's workers can't read it. This
# script runs as root and keeps a copy they can read, refreshed every few
# seconds, for /setup/token.txt; it also writes the setup-page allowlist and
# the explanatory page.
# Behind Umbrel's app_proxy /setup stays gated by the user's Umbrel login.

# Outside nginx's root, so only the /setup/token.txt location serves it.
TOKEN_COPY_DIR=/run/sc-gui-token
TOKEN_COPY="$TOKEN_COPY_DIR/token.txt"

write_setup_allowlist() {
    allow_file=/etc/nginx/setup-key-allow.conf
    tmp="${allow_file}.tmp"
    hosts="${SC_SETUP_KEY_ALLOW_HOSTS:-stable-channels-lsp_app_proxy_1 app_proxy}"

    resolve_host() {
        if command -v getent >/dev/null 2>&1; then
            getent hosts "$1" 2>/dev/null | awk '{print $1}'
        elif command -v nslookup >/dev/null 2>&1; then
            nslookup "$1" 2>/dev/null | awk '
                /^Address [0-9]+: / {print $3}
                /^Address: / && $2 !~ /:53$/ {print $2}
            '
        fi
    }

    {
        printf '# Generated by 40-provision-gui-token.sh.\n'
        for cidr in ${SC_SETUP_KEY_ALLOW_CIDRS:-}; do
            printf 'allow %s;\n' "$cidr"
        done
        for host in $hosts; do
            resolve_host "$host" | while read -r ip; do
                [ -n "$ip" ] && printf 'allow %s;\n' "$ip"
            done
        done
        printf 'deny all;\n'
    } | awk '!seen[$0]++' > "$tmp"

    mv -f "$tmp" "$allow_file"
}

# Prints the token path: SC_NETWORK, else /run/sc-lsp/network, else bitcoin, else the first dir that has it.
find_token_file() {
    preferred="${SC_NETWORK:-}"
    if [ -z "$preferred" ] && [ -s /run/sc-lsp/network ]; then
        preferred="$(sed -n '1p' /run/sc-lsp/network 2>/dev/null || true)"
    fi
    if [ -n "$preferred" ] && [ -e "/run/sc-lsp/${preferred}/gui.macaroon" ]; then
        printf '%s\n' "/run/sc-lsp/${preferred}/gui.macaroon"
        return 0
    fi
    if [ -e /run/sc-lsp/bitcoin/gui.macaroon ]; then
        printf '%s\n' /run/sc-lsp/bitcoin/gui.macaroon
        return 0
    fi
    for candidate in /run/sc-lsp/*/gui.macaroon; do
        [ -e "$candidate" ] || continue
        printf '%s\n' "$candidate"
        return 0
    done
    return 1
}

# Copies the current token where nginx can read it, or removes the copy while there is none.
refresh_token_copy() {
    if ! source_file="$(find_token_file)" || [ ! -s "$source_file" ]; then
        rm -f "$TOKEN_COPY"
        return 0
    fi
    cmp -s "$source_file" "$TOKEN_COPY" && return 0
    tmp="$TOKEN_COPY_DIR/.token.txt.tmp"
    if (umask 077 && cat "$source_file" > "$tmp") && chgrp nginx "$tmp" && chmod 0640 "$tmp" \
        && mv -f "$tmp" "$TOKEN_COPY"; then
        copy_failed=""
        return 0
    fi
    rm -f "$tmp"
    # Said once per failure streak, as this runs every few seconds.
    [ -n "${copy_failed:-}" ] || echo "40-provision-gui-token.sh: could not copy $source_file for /setup/token.txt" >&2
    copy_failed=1
}

write_setup_allowlist

mkdir -p "$TOKEN_COPY_DIR"
chgrp nginx "$TOKEN_COPY_DIR"
chmod 0750 "$TOKEN_COPY_DIR"
refresh_token_copy
# Keeps running beside nginx, which the entrypoint starts once this script returns.
(
    while :; do
        sleep 2
        refresh_token_copy
    done
) </dev/null &

# The token is deliberately not embedded here; the GUI fetches /setup/token.txt.
mkdir -p /usr/share/nginx/html/setup
cat > /usr/share/nginx/html/setup/index.html.tmp <<'EOF'
<!doctype html><meta charset="utf-8"><title>Stable Channels LSP — Setup</title>
<body style="font-family:system-ui;max-width:40em;margin:4em auto">
<h2>Operator access</h2>
<p>The dashboard signs in with the GUI admin token. That token can create and revoke other logins, so keep it private and never share it with wallet users.</p>
<p>Fetch it from <a href="/setup/token.txt">/setup/token.txt</a> while signed in to Umbrel, then paste it into the GUI sign-in screen. Use the Access page to make limited logins for other people.</p>
<p><a href="/">Open the GUI</a></p>
</body>
EOF
mv -f /usr/share/nginx/html/setup/index.html.tmp /usr/share/nginx/html/setup/index.html
