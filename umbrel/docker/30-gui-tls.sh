#!/bin/sh
# nginx docker-entrypoint.d hook: optional HTTPS listener on 8443 for servers outside Umbrel.
# Enabled by SC_GUI_TLS_CERT + SC_GUI_TLS_KEY (readable files) or SC_GUI_TLS=self-signed; else nothing; a bad pair, a bad value or a failed self-signed setup stops the container.

conf=/etc/nginx/conf.d/gui-tls.conf
tls_dir=/etc/nginx/tls
cert=""
key=""

rm -f "$conf"

# A half-set or unusable pair stops the container (a non-zero hook aborts nginx's entrypoint), so HTTPS is never silently off.
fail() {
    echo "30-gui-tls.sh: $1" >&2
    exit 1
}

if [ -n "${SC_GUI_TLS_CERT:-}${SC_GUI_TLS_KEY:-}" ]; then
    [ -n "${SC_GUI_TLS_CERT:-}" ] || fail "SC_GUI_TLS_KEY is set but SC_GUI_TLS_CERT is not"
    [ -n "${SC_GUI_TLS_KEY:-}" ] || fail "SC_GUI_TLS_CERT is set but SC_GUI_TLS_KEY is not"
    [ -s "$SC_GUI_TLS_CERT" ] && [ -r "$SC_GUI_TLS_CERT" ] || fail "SC_GUI_TLS_CERT ($SC_GUI_TLS_CERT) is missing, empty or unreadable"
    [ -s "$SC_GUI_TLS_KEY" ] && [ -r "$SC_GUI_TLS_KEY" ] || fail "SC_GUI_TLS_KEY ($SC_GUI_TLS_KEY) is missing, empty or unreadable"
    cert="$SC_GUI_TLS_CERT"
    key="$SC_GUI_TLS_KEY"
elif [ "${SC_GUI_TLS:-}" = "self-signed" ]; then
    cert="$tls_dir/gui.crt"
    key="$tls_dir/gui.key"
    if [ ! -s "$cert" ] || [ ! -s "$key" ]; then
        command -v openssl >/dev/null 2>&1 || fail "SC_GUI_TLS=self-signed needs openssl, which is missing"
        mkdir -p "$tls_dir" || fail "could not create $tls_dir for the self-signed certificate"
        if ! openssl req -x509 -newkey rsa:2048 -nodes -days 3650 \
            -subj "/CN=stable-channels-lsp" -keyout "$key" -out "$cert" >/dev/null 2>&1; then
            rm -f "$cert" "$key"
            fail "could not generate the self-signed certificate"
        fi
        [ -s "$cert" ] && [ -s "$key" ] || fail "the generated self-signed certificate or key is missing or empty"
        chmod 600 "$key"
    fi
elif [ -n "${SC_GUI_TLS:-}" ]; then
    fail "SC_GUI_TLS=$SC_GUI_TLS is not valid, the only allowed value is self-signed"
else
    exit 0
fi

cat > "$conf" <<EOF
# Generated by 30-gui-tls.sh.
server {
    listen 8443 ssl;
    ssl_certificate $cert;
    ssl_certificate_key $key;

    include /etc/nginx/conf.d/gui-locations.inc;
}
EOF
echo "30-gui-tls.sh: HTTPS enabled on 8443" >&2
